CREATE TABLE resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT resources_pk PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() CONSTRAINT resources_public_id_unique UNIQUE,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(64) NOT NULL,
    kind TEXT NOT NULL CONSTRAINT resources_kind_check
        CHECK (kind IN ('gpu', 'instrument', 'room', 'workstation')),
    location VARCHAR(255) NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT true,
    availability JSONB NOT NULL DEFAULT '[]'::jsonb
        CONSTRAINT resources_availability_array CHECK (jsonb_typeof(availability) = 'array'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT resources_code_normalized CHECK (code = upper(btrim(code)))
);

CREATE UNIQUE INDEX resources_code_unique ON resources (upper(btrim(code)));

CREATE TABLE resource_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT resource_requests_pk PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() CONSTRAINT resource_requests_public_id_unique UNIQUE,
    resource_id BIGINT NOT NULL CONSTRAINT resource_requests_resource_fk
        REFERENCES resources(id) ON DELETE RESTRICT,
    team_id BIGINT NOT NULL CONSTRAINT resource_requests_team_fk
        REFERENCES teams(id) ON DELETE RESTRICT,
    requested_by UUID NOT NULL CONSTRAINT resource_requests_user_fk
        REFERENCES public.users(user_id) ON DELETE RESTRICT,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    purpose VARCHAR(1000) NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CONSTRAINT resource_requests_status_check
        CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at TIMESTAMPTZ,
    CONSTRAINT resource_requests_interval_check CHECK (start_time < end_time),
    CONSTRAINT resource_requests_decision_check CHECK (
        (status = 'pending' AND decided_at IS NULL) OR
        (status IN ('approved', 'rejected') AND decided_at IS NOT NULL)
    )
);

CREATE INDEX resource_requests_resource_interval_idx
    ON resource_requests (resource_id, start_time, end_time)
    WHERE status = 'approved';
CREATE INDEX resource_requests_team_created_idx
    ON resource_requests (team_id, created_at DESC);
CREATE INDEX resource_requests_status_created_idx
    ON resource_requests (status, created_at DESC);

