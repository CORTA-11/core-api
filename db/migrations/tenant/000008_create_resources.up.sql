CREATE FUNCTION synodus_has_organization_membership()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path FROM CURRENT
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.users AS app_user
        JOIN public.org_user AS membership ON membership.user_id = app_user.id
        JOIN public.orgs AS organization ON organization.id = membership.org_id
        WHERE app_user.user_id = synodus_app_user_public_id()
          AND app_user.deleted_at IS NULL
          AND organization.schema_name = current_schema()
          AND organization.deleted_at IS NULL
          AND organization.lifecycle_state = 'active'
    );
$$;
ALTER FUNCTION synodus_has_organization_membership() OWNER TO synodus_owner;

CREATE FUNCTION synodus_current_organization_role()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path FROM CURRENT
AS $$
    SELECT membership.role
    FROM public.users AS app_user
    JOIN public.org_user AS membership ON membership.user_id = app_user.id
    JOIN public.orgs AS organization ON organization.id = membership.org_id
    WHERE app_user.user_id = synodus_app_user_public_id()
      AND organization.schema_name = current_schema()
      AND app_user.deleted_at IS NULL
      AND organization.deleted_at IS NULL;
$$;
ALTER FUNCTION synodus_current_organization_role() OWNER TO synodus_owner;

CREATE FUNCTION synodus_user_display_name(candidate UUID)
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path FROM CURRENT
AS $$
    SELECT display_name FROM public.users
    WHERE user_id = candidate AND deleted_at IS NULL;
$$;
ALTER FUNCTION synodus_user_display_name(UUID) OWNER TO synodus_owner;

CREATE POLICY resources_owner_maintenance ON resources
    FOR ALL TO synodus_owner USING (true) WITH CHECK (true);
CREATE POLICY resource_requests_owner_maintenance ON resource_requests
    FOR ALL TO synodus_owner USING (true) WITH CHECK (true);
CREATE POLICY resources_runtime_access ON resources
    FOR ALL TO synodus_runtime
    USING (synodus_has_organization_membership())
    WITH CHECK (synodus_has_organization_membership());
CREATE POLICY resource_requests_runtime_access ON resource_requests
    FOR ALL TO synodus_runtime
    USING (synodus_has_organization_membership())
    WITH CHECK (synodus_has_organization_membership());
-- Team identity (name/public id) is organization metadata. Team content remains
-- protected by team_members/tasks policies and exact-team authorization.
CREATE POLICY teams_runtime_organization_select ON teams
    FOR SELECT TO synodus_runtime
    USING (NOT is_quarantine AND synodus_has_organization_membership());

REVOKE ALL ON resources, resource_requests FROM PUBLIC, synodus_runtime;
REVOKE ALL ON resources_id_seq, resource_requests_id_seq FROM PUBLIC, synodus_runtime;
REVOKE ALL ON FUNCTION synodus_has_organization_membership() FROM PUBLIC;
REVOKE ALL ON FUNCTION synodus_current_organization_role() FROM PUBLIC;
REVOKE ALL ON FUNCTION synodus_user_display_name(UUID) FROM PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON resources, resource_requests TO synodus_runtime;
GRANT USAGE, SELECT ON resources_id_seq, resource_requests_id_seq TO synodus_runtime;
GRANT EXECUTE ON FUNCTION synodus_has_organization_membership() TO synodus_runtime;
GRANT EXECUTE ON FUNCTION synodus_current_organization_role() TO synodus_runtime;
GRANT EXECUTE ON FUNCTION synodus_user_display_name(UUID) TO synodus_runtime;
